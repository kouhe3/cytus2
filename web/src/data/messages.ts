export type Params = Readonly<Record<string, string | number>>;

export type Translate = (key: MessageKey, params?: Params) => string;

export interface I18n {
  readonly lang: Lang;
  readonly locale: string;
  readonly t: Translate;
  formatNumber(value: number, options?: Intl.NumberFormatOptions): string;
  formatDate(value: string | number | Date, options?: Intl.DateTimeFormatOptions): string;
}

/* --------------------------------------------------------------- numbering */

const GAME_TIMESTAMP =
  /^(\d{1,4})_(\d{1,2})_(\d{1,2})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2}))?)?$/;

const numberFormats = new Map<string, Intl.NumberFormat>();
const dateFormats = new Map<string, Intl.DateTimeFormat>();
const pluralRules = new Map<string, Intl.PluralRules>();

function numberFormatter(locale: string, options?: Intl.NumberFormatOptions) {
  const key = options ? `${locale}:${JSON.stringify(options)}` : locale;
  let formatter = numberFormats.get(key);
  if (!formatter) {
    formatter = new Intl.NumberFormat(locale, options);
    numberFormats.set(key, formatter);
  }
  return formatter;
}

function dateFormatter(locale: string, options: Intl.DateTimeFormatOptions) {
  const key = `${locale}:${JSON.stringify(options)}`;
  let formatter = dateFormats.get(key);
  if (!formatter) {
    formatter = new Intl.DateTimeFormat(locale, options);
    dateFormats.set(key, formatter);
  }
  return formatter;
}

/* --------------------------------------------------------------- translate */

const warned = new Set<string>();

function devWarn(message: string): void {
  if (!import.meta.env?.DEV) {
    return;
  }
  if (warned.has(message)) {
    return;
  }
  warned.add(message);
  console.warn(message);
}

function interpolate(template: string, params?: Params): string {
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    if (value === undefined) {
      devWarn(`[i18n] missing parameter "${name}" in "${template}"`);
      return match;
    }
    return String(value);
  });
}

/**
 * Missing keys fall back to zh-Hans and log a warning in development. A key
 * that is also absent from zh-Hans returns an empty string: the raw message key
 * must never reach the interface.
 */
export function translate(
  lang: Lang,
  key: MessageKey,
  params?: Params,
): string {
  const primary: string | undefined = MESSAGES[lang]?.[key];
  if (primary !== undefined) {
    return interpolate(primary, params);
  }
  const fallback: string | undefined = MESSAGES["zh-Hans"][key];
  devWarn(
    `[i18n] missing "${key}" in "${lang}"; falling back to zh-Hans`,
  );
  if (fallback === undefined) {
    devWarn(`[i18n] "${key}" is missing from the zh-Hans fallback dictionary`);
    return "";
  }
  return interpolate(fallback, params);
}

export function hasMessage(lang: Lang, key: string): boolean {
  return key in MESSAGES[lang];
}

/* ------------------------------------------------------------------- i18n */

export function createI18n(lang: Lang): I18n {
  const locale = LANG_LOCALES[lang];
  const t: Translate = (key, params) => translate(lang, key, params);
  return {
    lang,
    locale,
    t,
    formatNumber(value, options) {
      try {
        return numberFormatter(locale, options).format(value);
      } catch {
        return String(value);
      }
    },
    formatDate(value, options) {
      // Canonical OS logs use a game timestamp like `687_06_30 18:01:20`.
      // Unknown components are `?` and must stay literal, so only a fully
      // numeric timestamp is handed to Intl.
      const game = typeof value === "string" ? GAME_TIMESTAMP.exec(value) : null;
      let date: Date;
      let hasTime = false;
      if (game) {
        const [, year, month, day, hour, minute, second] = game;
        hasTime = hour !== undefined;
        date = new Date(
          Number(year),
          Number(month) - 1,
          Number(day),
          Number(hour ?? 0),
          Number(minute ?? 0),
          Number(second ?? 0),
        );
        // `new Date(12, ...)` maps years 0-99 to 1900+, so pin the parsed year.
        date.setFullYear(Number(year));
      } else {
        date =
          value instanceof Date
            ? value
            : new Date(value as string | number);
      }
      if (Number.isNaN(date.getTime())) {
        return String(value);
      }
      const resolved: Intl.DateTimeFormatOptions = options ?? {
        year: "numeric",
        month: "short",
        day: "numeric",
        ...(hasTime ? { hour: "2-digit", minute: "2-digit" } : {}),
      };
      try {
        return dateFormatter(locale, resolved).format(date);
      } catch {
        return String(value);
      }
    },
  };
}

